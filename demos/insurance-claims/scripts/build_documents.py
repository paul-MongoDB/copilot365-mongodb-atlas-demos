def channel_export() -> Path:
    """Backup copy of the five Teams posts as a Word file, in case Teams is not indexed yet.
    Written to fallback/, apart from the four Contoso documents in onedrive/."""
    import re
    text = (ROOT / "teams" / "TEAMS_MESSAGES.md").read_text()
    meta = [  # (subject, sender, date) in the order of the posts in TEAMS_MESSAGES.md
        ("CLM-2026-10482 Brennan: field inspection results", "Jordan Reyes (Field Adjuster)", "Thu Oct 22"),
        ("CLM-2026-10482 Brennan: needs your review", "Maya Chen (Desk Adjuster)", "Wed Oct 28"),
        ("LeafyDry on the Vendor Watch List", "Dana Brooks (SIU Investigator)", "Thu Oct 29"),
        ("Sewer backups on Shady Elm Ct", "Priya Nair (Desk Adjuster)", "Tue Oct 27"),
        ("CAT-2026-17 update", "Marcus Bell (Senior Adjuster)", "Tue Oct 27"),
    ]
    sections = re.split(r"^## Post \d+:.*$", text, flags=re.M)[1:]
    if len(meta) != len(sections):
        raise SystemExit(f"TEAMS_MESSAGES.md has {len(sections)} posts but build_documents.py "
                         f"has metadata for {len(meta)}. Update the meta list in channel_export().")
    doc = new_doc("DFW Property Claims: channel export",
                  "Team: Contoso Claims (DEMO). Channel: DFW Property Claims. Each post is shown "
                  "with its replies.")
    for (subject, sender, date), sec in zip(meta, sections):
        # First quote block is the post. A later block, after a line like
        # "**Reply from Paul (Team Lead), in the same thread:**", is a reply.
        replier = re.search(r"^\*\*Reply from (.+?), in the same thread:\*\*", sec, flags=re.M)
        blocks, cur = [], []
        for ln in sec.splitlines():
            if ln.startswith(">"):
                cur.append(ln[2:] if ln.startswith("> ") else "")
            elif cur:
                blocks.append(cur); cur = []
        if cur:
            blocks.append(cur)
        doc.add_heading(subject, level=2)
        meta_p = doc.add_paragraph(f"Posted by {sender}, {date}")
        meta_p.runs[0].italic = True
        for ln in blocks[0]:
            if ln.startswith("- "):
                doc.add_paragraph(ln[2:], style="List Bullet")
            elif ln.strip():
                doc.add_paragraph(ln)
        if len(blocks) > 1 and not replier:
            raise SystemExit(f"Post '{subject}' has a reply block but no "
                             "'**Reply from <name>, in the same thread:**' line.")
        for reply in blocks[1:]:
            r = doc.add_paragraph(f"Reply from {replier.group(1)}, {date}:")
            r.runs[0].italic = True
            doc.add_paragraph(" ".join(reply))
    out = ROOT / "fallback" / "DFW Property Claims channel export.docx"
    out.parent.mkdir(exist_ok=True)
    doc.save(out)
    return out


def main() -> None:
    OUT.mkdir(exist_ok=True)
    policy_form()
    water_backup_endorsement()
    guidelines()
    vendors()
    fallback = channel_export()
    for p in sorted(OUT.glob("*.docx")):
        print(p.relative_to(ROOT))
    print(fallback.relative_to(ROOT))


if __name__ == "__main__":
    # No options: this only makes --help print the description instead of running.
    argparse.ArgumentParser(description=__doc__,
                            formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    main()
